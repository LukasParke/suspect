#!/usr/bin/env node
// Generates the `suspect.*` settings from the configuration schema, so an
// editor setting cannot drift from the `.suspect.yaml` key it sets.
//
// Inputs: schemas/suspect.schema.json (written from suspect-config's setting
// table by `SUSPECT_BLESS=1 cargo test -p suspect-config --test json_schema`)
// and settings.editor.json (hand-written: settings with no config key).
// Outputs: package.json `contributes.configuration` and
// src/settings.generated.ts (one typed getter per setting).
//
// A schema property with `x-suspect-editor: {key, scope, aliases?}` becomes
// one setting named `key`; each alias (the key's older spelling) becomes a
// deprecated setting the getter still reads. Config-backed settings are
// `[T, "null"]` with default `null`: unset defers to the committed files.
//
//   node scripts/settings.cjs          print what would change, exit 1 on drift
//   node scripts/settings.cjs --write  rewrite both files (npm run settings:write)

const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.join(__dirname, '..');
const SCHEMA = path.join(ROOT, 'schemas', 'suspect.schema.json');
const EDITOR_ONLY = path.join(ROOT, 'settings.editor.json');
const MANIFEST = path.join(ROOT, 'package.json');
const GETTERS = path.join(ROOT, 'src', 'settings.generated.ts');
const WRITE_COMMAND = 'npm run settings:write';

const camel = (s) => s.replace(/[_.]([a-z])/g, (_, c) => c.toUpperCase());

/** Every exposed schema property with its path; deprecated spellings are skipped. */
function* exposed(node, at = []) {
	for (const [key, prop] of Object.entries(node.properties ?? {})) {
		if (prop.deprecated) continue;
		const next = [...at, key];
		if (prop['x-suspect-editor']) yield [next.join('.'), prop];
		if (prop.properties) yield* exposed(prop, next);
	}
}

/** The value shape of a property as a VS Code contribution (no default, no text). */
function shape(prop) {
	const out = { type: [prop.type === 'integer' ? 'integer' : prop.type, 'null'] };
	if (prop.enum) out.enum = [...prop.enum, null];
	for (const bound of ['minimum', 'maximum']) {
		if (prop[bound] !== undefined) out[bound] = prop[bound];
	}
	if (prop.items) out.items = valueShape(prop.items);
	if (prop.additionalProperties && typeof prop.additionalProperties === 'object') {
		out.additionalProperties = valueShape(prop.additionalProperties);
	}
	return out;
}

function valueShape(prop) {
	const out = { type: prop.type };
	if (prop.enum) out.enum = [...prop.enum];
	return out;
}

function shown(value) {
	return typeof value === 'string' ? value : JSON.stringify(value);
}

/** One config-backed setting and its deprecated spellings. */
function configSettings(schema) {
	const settings = [];
	for (const [configKey, prop] of exposed(schema)) {
		const editor = prop['x-suspect-editor'];
		const fallback = prop.default === undefined ? '' : ` (default \`${shown(prop.default)}\`)`;
		const contribution = {
			...shape(prop),
			default: null,
			markdownDescription: `${prop.description} \`${configKey}\` in \`.suspect.yaml\`; unset (\`null\`) uses the committed value${fallback}.`,
			scope: editor.scope,
		};
		settings.push({ key: editor.key, configKey, prop, contribution, aliases: editor.aliases ?? [] });
		for (const alias of editor.aliases ?? []) {
			settings.push({
				key: alias,
				deprecatedFor: editor.key,
				contribution: {
					...shape(prop),
					default: null,
					markdownDescription: `Deprecated: use \`${editor.key}\`.`,
					deprecationMessage: `Use ${editor.key} instead.`,
					scope: editor.scope,
				},
			});
		}
	}
	return settings;
}

/** The TypeScript type a contribution's value has. */
function tsType(contribution) {
	const types = [].concat(contribution.type).filter((t) => t !== 'null');
	const literal = (values) => values.filter((v) => v !== null).map((v) => JSON.stringify(v)).join(' | ');
	switch (types[0]) {
		case 'string':
			return contribution.enum ? literal(contribution.enum) : 'string';
		case 'boolean':
			return 'boolean';
		case 'integer':
		case 'number':
			return 'number';
		case 'array': {
			const item = contribution.items?.enum ? literal(contribution.items.enum) : tsType(contribution.items ?? { type: 'string' });
			return item.includes('|') ? `readonly (${item})[]` : `readonly ${item}[]`;
		}
		case 'object': {
			const inner = contribution.additionalProperties;
			return `Readonly<Record<string, ${inner ? tsType(inner) : 'unknown'}>>`;
		}
		default:
			throw new Error(`no TypeScript type for ${JSON.stringify(contribution.type)}`);
	}
}

function getterName(key) {
	return camel(key.replace(/^suspect\./, ''));
}

function typescript(configBacked, editorOnly) {
	const lines = [
		'// Generated by scripts/settings.cjs from schemas/suspect.schema.json and',
		`// settings.editor.json. Do not edit; run \`${WRITE_COMMAND}\`.`,
		'',
		"import * as vscode from 'vscode';",
		'',
		'/** A resource the setting is read for (resource-scoped settings), or none. */',
		'export type SettingScope = vscode.ConfigurationScope | undefined;',
		'',
		'function config(scope: SettingScope): vscode.WorkspaceConfiguration {',
		"\treturn vscode.workspace.getConfiguration('suspect', scope);",
		'}',
		'',
		'/** The first of `keys` that is set; blank strings and `null` are unset. */',
		'function first<T>(scope: SettingScope, keys: readonly string[]): T | null {',
		'\tconst settings = config(scope);',
		'\tfor (const key of keys) {',
		'\t\tconst value = settings.get<T | null>(key);',
		"\t\tif (value !== undefined && value !== null && value !== '') return value;",
		'\t}',
		'\treturn null;',
		'}',
		'',
		'/** A renamed setting: the old key, still read, and the key that replaced it. */',
		'export interface RenamedSetting {',
		'\treadonly from: string;',
		'\treadonly to: string;',
		'}',
		'',
		'/** Every renamed setting, full keys (`suspect.testBaseUrl` -> `suspect.test.baseUrl`). */',
		'export const RENAMED_SETTINGS: readonly RenamedSetting[] = [',
		...configBacked.filter((s) => s.deprecatedFor).map((s) => `\t{ from: '${s.key}', to: '${s.deprecatedFor}' },`),
		'];',
		'',
		'/** Editor setting -> the `.suspect.yaml` key it sets. */',
		'export const CONFIG_KEYS: Readonly<Record<string, string>> = {',
		...configBacked.filter((s) => s.configKey).map((s) => `\t'${s.key}': '${s.configKey}',`),
		'};',
	];
	for (const setting of configBacked.filter((s) => s.configKey)) {
		const keys = [setting.key, ...setting.aliases].map((k) => `'${k.replace(/^suspect\./, '')}'`);
		const type = tsType(setting.contribution);
		const old = setting.aliases.length ? `, then ${setting.aliases.map((a) => `\`${a}\``).join(', ')}` : '';
		lines.push(
			'',
			`/** \`${setting.key}\`${old}; \`${setting.configKey}\` in .suspect.yaml. \`null\`: unset, the committed value applies. */`,
			`export function ${getterName(setting.key)}(scope?: SettingScope): ${type} | null {`,
			`\treturn first<${type}>(scope, [${keys.join(', ')}]);`,
			'}',
		);
	}
	for (const [key, contribution] of Object.entries(editorOnly)) {
		const type = tsType(contribution);
		const fallback = JSON.stringify(contribution.default);
		const deprecated = contribution.deprecationMessage ? ' Deprecated.' : '';
		lines.push(
			'',
			`/** \`${key}\` (editor-only).${deprecated} */`,
			`export function ${getterName(key)}(scope?: SettingScope): ${type} {`,
			`\treturn config(scope).get<${type}>('${key.replace(/^suspect\./, '')}', ${fallback});`,
			'}',
		);
	}
	return lines.join('\n') + '\n';
}

/** Both outputs, from the files on disk. */
function generate() {
	const schema = JSON.parse(fs.readFileSync(SCHEMA, 'utf8'));
	const editorOnly = JSON.parse(fs.readFileSync(EDITOR_ONLY, 'utf8'));
	const configBacked = configSettings(schema);
	const properties = {};
	for (const setting of configBacked) properties[setting.key] = setting.contribution;
	for (const [key, contribution] of Object.entries(editorOnly)) {
		if (properties[key]) throw new Error(`${key} is both a config setting and in settings.editor.json`);
		properties[key] = contribution;
	}
	return {
		configuration: { title: 'Suspect', properties },
		typescript: typescript(configBacked, editorOnly),
	};
}

/** The checked-in package.json with the generated configuration in place. */
function manifestWith(configuration) {
	const manifest = JSON.parse(fs.readFileSync(MANIFEST, 'utf8'));
	manifest.contributes.configuration = configuration;
	// Tabs and key order as checked in.
	return JSON.stringify(manifest, null, '\t') + '\n';
}

module.exports = { generate, manifestWith, MANIFEST, GETTERS, WRITE_COMMAND };

if (require.main === module) {
	const { configuration, typescript: ts } = generate();
	const manifest = manifestWith(configuration);
	const stale = [
		[MANIFEST, manifest],
		[GETTERS, ts],
	].filter(([file, text]) => (fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : '') !== text);
	if (process.argv.includes('--write')) {
		for (const [file, text] of stale) {
			fs.writeFileSync(file, text);
			console.log(`wrote ${path.relative(ROOT, file)}`);
		}
	} else if (stale.length) {
		for (const [file] of stale) console.error(`${path.relative(ROOT, file)} is stale; run \`${WRITE_COMMAND}\``);
		process.exit(1);
	}
}
