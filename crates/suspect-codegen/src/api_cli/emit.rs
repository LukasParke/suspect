//! Emit one self-contained Go module: module metadata, the executable entry
//! point, the generated Cobra surface and the canonical SDK as an internal
//! package. Nothing here decides a public name or a wire semantic; both were
//! fixed during admission.
use std::{collections::BTreeMap, fmt::Write as _};

use super::{
    CliPlan, ConfirmationPolicy, OutputFormat, Representation, package,
    planning::{self, BoundCommand, BoundFlag, Group, Node, Payload},
    surface,
};
use crate::OutFile;

/// A Go string literal; JSON string escaping is a subset of Go's.
fn q(text: &str) -> String {
    serde_json::to_string(text).expect("Go string literal")
}

/// Collapse prose onto one line so it can never break a generated comment.
fn prose(text: &str) -> String {
    text.replace(['\n', '\r'], " ").replace("*/", "* /")
}

pub(super) fn artifacts(plan: &CliPlan) -> Vec<OutFile> {
    // The SDK becomes a package of this one module, so its own module file is
    // dropped: a nested go.mod would make the embedded package unbuildable.
    let mut files: BTreeMap<String, String> = plan
        .sdk_files
        .iter()
        .filter_map(|file| {
            let relative = file
                .path
                .strip_prefix("go/")
                .expect("canonical Go SDK artifact");
            (relative != "go.mod")
                .then(|| (format!("internal/sdk/{relative}"), file.content.clone()))
        })
        .collect();
    for file in package::artifacts(plan) {
        files.insert(file.path, file.content);
    }
    files.insert(
        format!("cmd/{}/main.go", plan.config.binary_name),
        entry_point(plan),
    );
    files.insert(
        "internal/cli/runtime.go".into(),
        include_str!("runtime.go").into(),
    );
    files.insert("internal/cli/commands.go".into(), commands(plan));
    let manifest = surface::artifact(plan);
    files.insert(manifest.path, manifest.content);
    files
        .into_iter()
        .map(|(path, content)| OutFile { path, content })
        .collect()
}

fn sdk_import(plan: &CliPlan) -> String {
    format!("{}/internal/sdk", plan.config.module_path)
}

fn entry_point(plan: &CliPlan) -> String {
    let binary = &plan.config.binary_name;
    format!(
        "// Code generated by suspect. DO NOT EDIT.\n\n\
         // Command {binary} is the generated API command-line application. It owns no\n\
         // API semantics: the command surface lives in internal/cli and every HTTP,\n\
         // authentication, validation and exact JSON decision lives in internal/sdk.\n\
         package main\n\n\
         import (\n\t\"os\"\n\n\t{}\n)\n\n\
         func main() {{\n\tos.Exit(cli.Execute(os.Args[1:], os.Stdin, os.Stdout, os.Stderr))\n}}\n",
        q(&format!("{}/internal/cli", plan.config.module_path))
    )
}

fn commands(plan: &CliPlan) -> String {
    let declares_failures = plan
        .commands
        .iter()
        .any(|command| command.responses.iter().any(|response| response.failure));
    let mut code =
        String::from("// Code generated by suspect. DO NOT EDIT.\n\npackage cli\n\nimport (\n");
    if declares_failures {
        code.push_str("\t\"errors\"\n");
    }
    let _ = writeln!(
        code,
        "\t\"time\"\n\n\t\"github.com/spf13/cobra\"\n\tsdk {}\n)\n",
        q(&sdk_import(plan))
    );
    let _ = write!(
        code,
        "// Generated runtime policy, compiled from the application target configuration.\n\
         // Callers of this executable cannot raise any of these bounds.\n\
         const (\n\
         \trequestDeadline = {} * time.Millisecond\n\
         \tmaxInputBytes   = {}\n\
         \toutputIndented  = {}\n\
         )\n\n",
        plan.config.runtime.request_deadline_ms,
        plan.config.runtime.max_input_bytes,
        matches!(plan.config.output.format, OutputFormat::PrettyJson)
    );
    let _ = writeln!(code, "const rootLong = {}\n", q(&root_long(plan)));
    code.push_str(&root_command(plan));
    code.push_str(&client_options());
    for command in &plan.commands {
        code.push_str(&leaf(plan, command));
    }
    for command in &plan.commands {
        code.push_str(&reporter(command));
    }
    code
}

/// The root command's long help: what the application is, how it reports, what
/// every exit code means, and which environment variables carry credentials.
fn root_long(plan: &CliPlan) -> String {
    let mut text = format!("{}\n\n", plan.mapping.description);
    text.push_str(
        "Machine output is exact JSON written to standard output; every diagnostic is\n\
         written to standard error. Numbers keep their exact source tokens.\n\n\
         Exit codes:\n\
         \u{20} exit 0  the request succeeded, or the command needed no request\n\
         \u{20} exit 1  runtime failure: transport, deadline, cancellation, codec or output\n\
         \u{20} exit 2  usage failure: the invocation was refused before anything was sent\n\
         \u{20} exit 3  documented API failure: the API returned a response the contract\n\
         \u{20}         declares as a failure; its exact document is on standard output\n\n",
    );
    match (&plan.config.credential_env, &plan.credential_factory) {
        (Some(policy), Some(_)) => {
            text.push_str(
                "Credentials come only from these environment variables. The embedded SDK\n\
                 reads them when an API command runs, never during help or completion:\n",
            );
            for (scheme, variable) in &policy.schemes {
                let _ = writeln!(
                    text,
                    "  {variable} supplies the source security scheme {}",
                    q(scheme)
                );
            }
            text.push('\n');
        }
        _ => text.push_str(
            "This application is anonymous: no credential environment policy is configured,\n\
             so no credential is ever read or sent.\n\n",
        ),
    }
    let _ = write!(
        text,
        "Every request uses a {}ms deadline and stops on SIGINT or SIGTERM. No request is\n\
         retried and no pagination is traversed.",
        plan.config.runtime.request_deadline_ms
    );
    text
}

fn root_command(plan: &CliPlan) -> String {
    let mut code = format!(
        "// newRootCommand builds the whole mapped command tree. It constructs no\n\
         // credentials and contacts no network; help and completion are complete here.\n\
         func newRootCommand(streams *Streams) *cobra.Command {{\n\
         \troot := &cobra.Command{{\n\
         \t\tUse: {},\n\
         \t\tLong: rootLong,\n\
         \t\tVersion: {},\n\
         \t\tArgs: cobra.NoArgs,\n\
         \t\tRunE: showHelp,\n\
         \t}}\n\
         \troot.PersistentFlags().String(serverFlagName, \"\", {})\n",
        q(&plan.config.binary_name),
        q(&plan.config.version),
        q(
            "Absolute base URL override, including its path prefix. Empty selects the source server."
        )
    );
    let mut group = 0usize;
    children(
        plan,
        &planning::tree(&plan.commands),
        "root",
        &mut group,
        &mut code,
    );
    code.push_str("\treturn root\n}\n\n");
    code
}

/// Attach one group's children in stable name order.
fn children(plan: &CliPlan, group: &Group, parent: &str, counter: &mut usize, code: &mut String) {
    for (name, node) in &group.children {
        match node {
            Node::Leaf(index) => {
                let _ = writeln!(
                    code,
                    "\t{parent}.AddCommand(new{}Command(streams))",
                    plan.commands[*index].symbol
                );
            }
            Node::Group(nested) => {
                *counter += 1;
                let variable = format!("group{counter}");
                let _ = writeln!(
                    code,
                    "\t{variable} := &cobra.Command{{Use: {}, Short: {}, Args: cobra.NoArgs, RunE: showHelp}}",
                    q(name),
                    q(&format!("{name} commands"))
                );
                children(plan, nested, &variable, counter, code);
                let _ = writeln!(code, "\t{parent}.AddCommand({variable})");
            }
        }
    }
}

fn client_options() -> String {
    "// clientOptions carries only explicit server selection. Credentials never pass\n\
     // through the command layer; the embedded SDK owns every credential decision.\n\
     func clientOptions(cmd *cobra.Command) sdk.ClientOptions {\n\
     \tserver, _ := cmd.Flags().GetString(serverFlagName)\n\
     \treturn sdk.ClientOptions{ServerURL: server}\n\
     }\n\n"
        .to_owned()
}

/// The flag's `--help` usage text, naming requiredness and exact representation.
fn usage(flag: &BoundFlag) -> String {
    let mut text = prose(&flag.description);
    if matches!(flag.representation, Representation::Integer) {
        text.push_str(" Accepts one exact integer token.");
    }
    if matches!(flag.representation, Representation::Number) {
        text.push_str(" Accepts one exact number token.");
    }
    if flag.required {
        text.push_str(" (required)");
    }
    text
}

#[allow(clippy::too_many_lines)]
fn leaf(plan: &CliPlan, command: &BoundCommand) -> String {
    let operation = &plan.sdk.operations()[command.operation];
    let target = format!(
        "{} {} ({})",
        operation.wire().method().as_str(),
        operation.wire().path(),
        operation.operation_id
    );
    let mut long = format!("{}\n\nTarget operation: {target}.", command.description);
    if let ConfirmationPolicy::Required { token } = &command.confirmation {
        let _ = write!(
            long,
            "\n\nThis operation requires explicit confirmation: pass --{} {token}, or\n--{} - to read the token from standard input.",
            planning::CONFIRM_FLAG,
            planning::CONFIRM_FLAG
        );
    }

    let mut inputs = String::new();
    let mut optionals = String::new();
    let mut required: Vec<String> = Vec::new();
    for (index, flag) in command.flags.iter().enumerate() {
        if flag.required {
            inputs.push_str(&required_flag(index, flag));
            required.push(format!("value{index}"));
        } else {
            optionals.push_str(&optional_flag(index, flag));
        }
    }
    if let Some(body) = &command.body {
        let index = command.flags.len();
        let read = format!(
            "\t\t\traw{index}, err := readDocument(streams, path{index}, maxInputBytes)\n\
             \t\t\tif err != nil {{\n\t\t\t\treturn err\n\t\t\t}}\n"
        );
        if body.required {
            let _ = write!(
                inputs,
                "\t\t\tpath{index}, set{index}, err := changedString(cmd, bodyFlagName)\n\
                 \t\t\tif err != nil {{\n\t\t\t\treturn err\n\t\t\t}}\n\
                 \t\t\tif !set{index} {{\n\t\t\t\treturn usagef(\"--%s is required for %s; use - to read standard input\", bodyFlagName, target)\n\t\t\t}}\n\
                 {read}\
                 \t\t\tvalue{index}, err := sdk.Codecs.{}.Decode(raw{index})\n\
                 \t\t\tif err != nil {{\n\t\t\t\treturn usagef(\"--%s is not a valid document for %s: %v\", bodyFlagName, target, err)\n\t\t\t}}\n",
                body.model
            );
            required.push(format!("value{index}"));
        } else {
            let _ = write!(
                optionals,
                "\t\t\t{{\n\
                 \t\t\t\tpath{index}, set{index}, err := changedString(cmd, bodyFlagName)\n\
                 \t\t\t\tif err != nil {{\n\t\t\t\t\treturn err\n\t\t\t\t}}\n\
                 \t\t\t\tif set{index} {{\n\
                 \t{read}\
                 \t\t\t\t\tvalue, err := sdk.Codecs.{}.Decode(raw{index})\n\
                 \t\t\t\t\tif err != nil {{\n\t\t\t\t\t\treturn usagef(\"--%s is not a valid document for %s: %v\", bodyFlagName, target, err)\n\t\t\t\t\t}}\n\
                 \t\t\t\t\tinput = input.{}(value)\n\
                 \t\t\t\t}}\n\t\t\t}}\n",
                body.model,
                body.setter_name
                    .as_deref()
                    .expect("optional body has a setter")
            );
        }
    }

    let mut code = format!(
        "// new{}Command runs {target}.\n\
         func new{}Command(streams *Streams) *cobra.Command {{\n\
         \tcmd := &cobra.Command{{\n\
         \t\tUse: {},\n\
         \t\tShort: {},\n\
         \t\tLong: {},\n\
         \t\tArgs: cobra.NoArgs,\n\
         \t\tRunE: func(cmd *cobra.Command, _ []string) error {{\n\
         \t\t\tconst target = {}\n",
        command.symbol,
        command.symbol,
        q(command.path.last().expect("admitted command path")),
        q(&prose(&command.summary)),
        q(&long),
        q(&target)
    );
    if let ConfirmationPolicy::Required { token } = &command.confirmation {
        // Confirmation precedes every flag read, so an unconfirmed invocation
        // never even consumes the caller's standard input.
        let _ = writeln!(
            code,
            "\t\t\tif err := confirmRequired(cmd, streams, target, {}); err != nil {{\n\t\t\t\treturn err\n\t\t\t}}",
            q(token)
        );
    }
    code.push_str(&inputs);
    let _ = writeln!(
        code,
        "\t\t\tinput := sdk.{}({})",
        operation.input_constructor,
        required.join(", ")
    );
    code.push_str(&optionals);
    let _ = write!(
        code,
        "\t\t\tclient, err := {}\n\
         \t\t\tif err != nil {{\n\t\t\t\treturn usagef(\"cannot construct the API client for %s; check --%s: %v\", target, serverFlagName, err)\n\t\t\t}}\n\
         \t\t\tdefer client.CloseIdleConnections()\n\
         \t\t\tctx, cancel := callContext(cmd.Context())\n\
         \t\t\tdefer cancel()\n\
         \t\t\treply, err := client.{}(ctx, input)\n\
         \t\t\tif err != nil {{\n\t\t\t\treturn report{}(streams, target, err)\n\t\t\t}}\n\
         \t\t\tdefer func() {{ _ = reply.Close() }}()\n",
        client_call(plan),
        operation.method_name,
        command.symbol
    );
    let successes: Vec<_> = command
        .responses
        .iter()
        .filter(|response| response.success)
        .collect();
    if successes.is_empty() {
        code.push_str("\t\t\t_ = reply\n");
    } else {
        code.push_str("\t\t\tswitch value := reply.(type) {\n");
        for response in successes {
            let _ = writeln!(code, "\t\t\tcase sdk.{}:", response.type_name);
            match response.payload {
                Payload::NoContent => {
                    code.push_str("\t\t\t\t_ = value\n\t\t\t\treturn nil\n");
                }
                Payload::ExactJson => {
                    let _ = write!(
                        code,
                        "\t\t\t\tdocument, err := sdk.Codecs.{}.Encode(value.Data)\n\
                         \t\t\t\tif err != nil {{\n\t\t\t\t\treturn failuref(err, \"cannot encode the exact %s document\", target)\n\t\t\t\t}}\n\
                         \t\t\t\treturn writeDocument(streams, document)\n",
                        response
                            .model
                            .as_deref()
                            .expect("exact JSON response has a codec")
                    );
                }
            }
        }
        code.push_str("\t\t\t}\n");
    }
    code.push_str(
        "\t\t\treturn failuref(nil, \"%s returned an undeclared representation\", target)\n\
         \t\t},\n\t}\n",
    );
    for flag in &command.flags {
        let text = q(&usage(flag));
        match flag.representation {
            Representation::Boolean => {
                let _ = writeln!(code, "\tcmd.Flags().Bool({}, false, {text})", q(&flag.flag));
            }
            _ => {
                let _ = writeln!(
                    code,
                    "\tcmd.Flags().String({}, \"\", {text})",
                    q(&flag.flag)
                );
            }
        }
    }
    if let Some(body) = &command.body {
        let mut text = format!(
            "Path to the finite {} request document; - reads standard input.",
            body.media_type
        );
        if body.required {
            text.push_str(" (required)");
        }
        let _ = writeln!(
            code,
            "\tcmd.Flags().String(bodyFlagName, \"\", {})",
            q(&text)
        );
    }
    if let ConfirmationPolicy::Required { token } = &command.confirmation {
        let _ = writeln!(
            code,
            "\tcmd.Flags().String(confirmFlagName, \"\", {})",
            q(&format!(
                "Confirmation token {token:?}; - reads the token from the first line of standard input. (required)"
            ))
        );
    }
    code.push_str("\treturn cmd\n}\n\n");
    code
}

/// The complete SDK client construction expression: the allocated environment
/// factory when a credential policy is configured, otherwise the explicit
/// anonymous constructor. Either way the command layer supplies no secret.
fn client_call(plan: &CliPlan) -> String {
    match &plan.credential_factory {
        Some(factory) => format!("sdk.{factory}(clientOptions(cmd))"),
        None => "sdk.NewClient(sdk.Credentials{}, clientOptions(cmd))".to_owned(),
    }
}

fn required_flag(index: usize, flag: &BoundFlag) -> String {
    let model = &flag.model;
    let name = q(&flag.flag);
    let read = match flag.representation {
        Representation::Boolean => {
            format!("\t\t\ttruth{index}, set{index}, err := changedBool(cmd, {name})\n")
        }
        _ => format!("\t\t\ttext{index}, set{index}, err := changedString(cmd, {name})\n"),
    };
    let mut code = format!(
        "{read}\
         \t\t\tif err != nil {{\n\t\t\t\treturn err\n\t\t\t}}\n\
         \t\t\tif !set{index} {{\n\t\t\t\treturn usagef(\"--{} is required for %s\", target)\n\t\t\t}}\n",
        flag.flag
    );
    let source = match flag.representation {
        Representation::Boolean => format!("truth{index}"),
        Representation::String => format!("text{index}"),
        Representation::Integer | Representation::Number => {
            let _ = write!(
                code,
                "\t\t\ttoken{index}, err := sdk.{}(text{index})\n\
                 \t\t\tif err != nil {{\n\t\t\t\treturn usagef(\"--{} is not {} for %s: %v\", target, err)\n\t\t\t}}\n",
                tokenizer(flag.representation),
                flag.flag,
                article(flag.representation)
            );
            format!("token{index}")
        }
    };
    let _ = write!(
        code,
        "\t\t\tvalue{index}, err := sdk.Codecs.{model}.DecodeValue({source})\n\
         \t\t\tif err != nil {{\n\t\t\t\treturn usagef(\"--{} is not a valid value for %s: %v\", target, err)\n\t\t\t}}\n",
        flag.flag
    );
    code
}

fn optional_flag(index: usize, flag: &BoundFlag) -> String {
    let model = &flag.model;
    let name = q(&flag.flag);
    let read = match flag.representation {
        Representation::Boolean => {
            format!("\t\t\t\ttruth{index}, set{index}, err := changedBool(cmd, {name})\n")
        }
        _ => format!("\t\t\t\ttext{index}, set{index}, err := changedString(cmd, {name})\n"),
    };
    let mut code = format!(
        "\t\t\t{{\n{read}\
         \t\t\t\tif err != nil {{\n\t\t\t\t\treturn err\n\t\t\t\t}}\n\
         \t\t\t\tif set{index} {{\n"
    );
    let source = match flag.representation {
        Representation::Boolean => format!("truth{index}"),
        Representation::String => format!("text{index}"),
        Representation::Integer | Representation::Number => {
            let _ = write!(
                code,
                "\t\t\t\t\ttoken, err := sdk.{}(text{index})\n\
                 \t\t\t\t\tif err != nil {{\n\t\t\t\t\t\treturn usagef(\"--{} is not {} for %s: %v\", target, err)\n\t\t\t\t\t}}\n",
                tokenizer(flag.representation),
                flag.flag,
                article(flag.representation)
            );
            "token".to_owned()
        }
    };
    let _ = write!(
        code,
        "\t\t\t\t\tvalue, err := sdk.Codecs.{model}.DecodeValue({source})\n\
         \t\t\t\t\tif err != nil {{\n\t\t\t\t\t\treturn usagef(\"--{} is not a valid value for %s: %v\", target, err)\n\t\t\t\t\t}}\n\
         \t\t\t\t\tinput = input.{}(value)\n\
         \t\t\t\t}}\n\t\t\t}}\n",
        flag.flag,
        flag.setter_name
            .as_deref()
            .expect("optional parameters have an allocated setter")
    );
    code
}

/// The SDK's exact token parser for a numeric flag. No float ever appears, so
/// a large integer literal survives unchanged.
fn tokenizer(representation: Representation) -> &'static str {
    match representation {
        Representation::Integer => "ParseInteger",
        _ => "ParseNumber",
    }
}

fn article(representation: Representation) -> &'static str {
    match representation {
        Representation::Integer => "an exact integer",
        _ => "an exact number",
    }
}

/// One reporter per command: a documented API failure writes its exact
/// document and becomes its own exit-code category; everything else is a
/// runtime failure.
fn reporter(command: &BoundCommand) -> String {
    let mut code = format!(
        "// report{} writes a documented failure's exact document and classifies it.\n\
         // Every other failure is a runtime failure with no machine output.\n\
         func report{}(streams *Streams, target string, err error) error {{\n",
        command.symbol, command.symbol
    );
    for response in command.responses.iter().filter(|r| r.failure) {
        let _ = write!(
            code,
            "\t{{\n\t\tvar declared *sdk.{}\n\t\tif errors.As(err, &declared) {{\n\
             \t\t\tdefer func() {{ _ = declared.Close() }}()\n",
            response.type_name
        );
        if let Payload::ExactJson = response.payload {
            let _ = write!(
                code,
                "\t\t\tdocument, encodeErr := sdk.Codecs.{}.Encode(declared.Data)\n\
                 \t\t\tif encodeErr != nil {{\n\t\t\t\treturn failuref(encodeErr, \"cannot encode the exact %s failure document\", target)\n\t\t\t}}\n\
                 \t\t\tif writeErr := writeDocument(streams, document); writeErr != nil {{\n\t\t\t\treturn writeErr\n\t\t\t}}\n",
                response
                    .model
                    .as_deref()
                    .expect("exact JSON response has a codec")
            );
        }
        code.push_str(
            "\t\t\treturn &documented{target: target, status: declared.Status}\n\t\t}\n\t}\n",
        );
    }
    code.push_str("\treturn transportFailure(target, err)\n}\n\n");
    code
}
