fn model(name: &str, attrs: &BTreeMap<String, Attribute>) -> String {
    let mut code = format!(
        "// {name}Model preserves Terraform known/null/unknown states.\ntype {name}Model struct {{\n"
    );
    for (attr, a) in attrs {
        code.push_str(&format!(
            " {} types.{} `tfsdk:{}`\n",
            attribute_field(attrs, attr),
            a.r#type.go(),
            q(attr)
        ));
    }
    code.push_str("}\n");
    code
}

fn schema(
    name: &str,
    description: &str,
    attrs: &BTreeMap<String, Attribute>,
    identity: Option<&str>,
    data: bool,
) -> String {
    let namespace = if data { "datasource" } else { "resource" };
    let mut code = format!(
        "func (r *{name}) Schema(_ context.Context, _ {namespace}.SchemaRequest, resp *{namespace}.SchemaResponse) {{\n resp.Schema = schema.Schema{{MarkdownDescription: {}, Attributes: map[string]schema.Attribute{{\n",
        q(description)
    );
    for (key, a) in attrs {
        let mut modifiers = Vec::new();
        let primitive = a.r#type.go().to_ascii_lowercase();
        if a.requires_replace {
            modifiers.push(format!("{primitive}planmodifier.RequiresReplace()"));
        }
        if identity == Some(key.as_str()) {
            modifiers.push("stringplanmodifier.UseStateForUnknown()".into());
        }
        code.push_str(&format!(" {}: schema.{}Attribute{{MarkdownDescription: {}, Required: {}, Optional: {}, Computed: {}, Sensitive: {},", q(key), a.r#type.go(), q(&a.description), a.mode == AttributeMode::Required, matches!(a.mode, AttributeMode::Optional | AttributeMode::OptionalComputed), a.mode.computed(), a.sensitive));
        if !data {
            code.push_str(&format!("WriteOnly: {},", a.write_only));
        }
        if !modifiers.is_empty() {
            code.push_str(&format!(
                "PlanModifiers: []planmodifier.{}{{{}}},",
                a.r#type.go(),
                modifiers.join(",")
            ));
        }
        code.push_str("},\n");
    }
    code.push_str(" }}\n}\n");
    code
}

