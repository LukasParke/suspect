fn validate_config(name: &str, mapping: &ResourceMapping) -> String {
    let attrs = &mapping.attributes;
    let mut code = format!(
        "func (r *{name}) ValidateConfig(ctx context.Context, req resource.ValidateConfigRequest, resp *resource.ValidateConfigResponse) {{\n var config {name}Model\n resp.Diagnostics.Append(req.Config.Get(ctx, &config)...)\n if resp.Diagnostics.HasError() {{ return }}\n"
    );
    for i in &mapping.update.inputs {
        if let InputWhen::TriggerChanged { attribute } = &i.when {
            let secret = attribute_field(attrs, &i.attribute);
            let trigger = attribute_field(attrs, attribute);
            code.push_str(&format!(" if !config.{secret}.IsNull() && !config.{secret}.IsUnknown() && config.{trigger}.IsNull() {{ resp.Diagnostics.AddAttributeError(path.Root({}), \"Missing write-only trigger\", \"A configured write-only value requires its explicit version trigger.\") }}\n", q(attribute)));
        }
    }
    code.push_str("}\n");
    code
}

