//! Terraform glue over typed SDK operations. No HTTP runtime is emitted here.
use std::collections::BTreeMap;

use super::{native::Presence, planning::*, *};

pub(super) fn q(value: &str) -> String {
    // JSON string escaping is also a safe Go interpreted string literal.
    serde_json::to_string(value).expect("string encoding")
}

pub(super) fn artifacts(plan: &ProviderPlan) -> Vec<OutFile> {
    let mut files: BTreeMap<_, _> = plan
        .sdk_files
        .iter()
        .map(|f| (f.path.clone(), f.content.clone()))
        .collect();
    let config = &plan.config;
    for file in super::package::artifacts(plan) {
        files.insert(file.path, file.content);
    }
    files.insert("terraform/main.go".into(), format!("// Code generated by suspect. DO NOT EDIT.\npackage main\n\nimport (\n \"context\"\n \"log\"\n \"github.com/hashicorp/terraform-plugin-framework/providerserver\"\n generated {}\n)\n\nfunc main() {{\n if err := providerserver.Serve(context.Background(), generated.New({}), providerserver.ServeOpts{{Address: {}}}); err != nil {{ log.Fatal(err) }}\n}}\n", q(&format!("{}/provider", config.module_path)), q(&config.version), q(&config.provider_address)));
    files.insert("terraform/provider/provider.go".into(), provider(plan));
    for bound in &plan.resources {
        let mapping = &plan.profile.resources[&bound.name];
        files.insert(
            format!("terraform/provider/resource_{}.go", bound.name),
            resource(plan, bound, mapping),
        );
    }
    for bound in &plan.data_sources {
        let mapping = &plan.profile.data_sources[&bound.name];
        files.insert(
            format!("terraform/provider/data_source_{}.go", bound.name),
            data_source(plan, bound, mapping),
        );
    }
    for file in super::docs::artifacts(plan) {
        files.insert(file.path, file.content);
    }
    files
        .into_iter()
        .map(|(path, content)| OutFile { path, content })
        .collect()
}

