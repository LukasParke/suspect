//! TypeScript emitter: interfaces, discriminated unions with type guards,
//! branded refinement types, and an optional Zod twin.

use std::collections::BTreeSet;

use crate::stg::{Base, Graph, StgNode, StgPrim, StgType, WellKnownFormat};

/// Emission options for the TypeScript target.
#[derive(Debug, Clone, Default)]
pub struct TsOptions {
    /// Emit a Zod schema twin per type (`schemas.ts` + inline parse helpers).
    pub zod: bool,
}

/// Emits all TypeScript source files for `graph`.
///
/// Files are returned as `(path, content)` pairs with deterministic order:
/// `types.ts`, `guards.ts`, optional `zod.ts`, `client.ts`.
pub fn emit_ts(graph: &Graph, opts: &TsOptions) -> Vec<(String, String)> {
    let mut files = Vec::new();
    let mut types = String::from("// Generated by suspect-codegen. Do not edit.\n");
    let mut guards = String::from("// Type guards for discriminated unions.\n");

    // Branded refinement types collected while walking primitives.
    let mut brands: BTreeSet<String> = BTreeSet::new();

    // Topological order keeps references forward-free.
    for name in &graph.topo_order {
        let Some(node) = graph.components.get(name) else {
            continue;
        };
        match node {
            StgNode::Struct(s) => {
                types.push_str(&format!("export interface {} {{\n", s.name.pascal));
                for f in &s.fields {
                    if let Some(d) = &f.docs {
                        for line in d.lines() {
                            types.push_str(&format!("  /// {line}\n"));
                        }
                    }
                    types.push_str(&format!(
                        "  {}{}: {};\n",
                        f.ident.camel,
                        if f.required { "" } else { "?" },
                        ts_type(&f.ty, &mut brands)
                    ));
                }
                types.push_str("}\n\n");
            }
            StgNode::StringEnum(e) => {
                let lits: Vec<String> = e
                    .variants
                    .iter()
                    .map(|(lit, _)| format!("  {}", quote_ts(lit)))
                    .collect();
                types.push_str(&format!(
                    "export type {} =\n{}\n;\n\n",
                    e.name.pascal,
                    lits.join(" |\n")
                ));
            }
            StgNode::Sum(sum) => {
                // Discriminated union over variant payloads keyed by tag field.
                let mut arms = Vec::new();
                for (value, payload) in &sum.variants {
                    let payload_ref = payload.pascal.clone();
                    arms.push(format!(
                        "  | ({{ {}: {} }} & {})",
                        sum.tag_field,
                        quote_ts(value),
                        payload_ref
                    ));
                }
                types.push_str(&format!(
                    "export type {} =\n{}\n;\n\n",
                    sum.name.pascal,
                    arms.join("\n")
                ));
                guards.push_str(&format!(
                    "export function is{0}(v: unknown): v is {0} {{\n",
                    sum.name.pascal
                ));
                guards.push_str(&format!(
                    "  return typeof v === 'object' && v !== null && '{}' in v;\n}}\n\n",
                    sum.tag_field
                ));
            }
            StgNode::Union(u) => {
                let members: Vec<String> =
                    u.members.iter().map(|m| ts_type(m, &mut brands)).collect();
                types.push_str(&format!(
                    "export type {} =\n  {}\n;\n\n",
                    u.name.pascal,
                    members.join("\n  | ")
                ));
            }
            StgNode::Alias(ty) => {
                types.push_str(&format!(
                    "export type {} = {};\n\n",
                    name_pascal_of(name),
                    ts_type(ty, &mut brands)
                ));
            }
        }
    }

    // Branded refinement declarations.
    if !brands.is_empty() {
        let mut header = String::from(
            "// Branded scalar types derived from schema constraints.\ndeclare const __brand: unique symbol;\ntype Brand<T, B extends string> = T & { readonly [__brand]: B };\n\n",
        );
        for b in &brands {
            header.push_str(b);
            header.push('\n');
        }
        types.insert_str(0, &header);
    }

    files.push(("types.ts".into(), types));
    files.push(("guards.ts".into(), guards));

    if opts.zod {
        files.push(zod_twin(graph));
    }
    files.push(ts_client(graph));
    files
}

fn name_pascal_of(component: &str) -> String {
    crate::stg::Ident::new(component).pascal
}

/// Renders a [`StgType`] as TypeScript, collecting branded names.
fn ts_type(ty: &StgType, brands: &mut BTreeSet<String>) -> String {
    match ty {
        StgType::Named(n) => crate::stg::Ident::new(n).pascal,
        StgType::InlineStruct(s) => {
            // Inline anonymous structs render as object literal types.
            let fields: Vec<String> = s
                .fields
                .iter()
                .map(|f| {
                    format!(
                        "{}{}: {}",
                        f.ident.camel,
                        if f.required { "" } else { "?" },
                        ts_type(&f.ty, brands)
                    )
                })
                .collect();
            format!("{{ {} }}", fields.join("; "))
        }
        StgType::InlineEnum(e) => e
            .variants
            .iter()
            .map(|(lit, _)| quote_ts(lit))
            .collect::<Vec<_>>()
            .join(" | "),
        StgType::InlineSum(s) => s
            .variants
            .iter()
            .map(|(value, payload)| {
                format!(
                    "({{ {}: {} }} & {})",
                    s.tag_field,
                    quote_ts(value),
                    payload.pascal
                )
            })
            .collect::<Vec<_>>()
            .join(" | "),
        StgType::InlineUnion(u) => u
            .members
            .iter()
            .map(|m| ts_type(m, brands))
            .collect::<Vec<_>>()
            .join(" | "),
        StgType::List(inner) => format!("{}[]", ts_type(inner, brands)),
        StgType::Dict(inner) => format!("Record<string, {}>", ts_type(inner, brands)),
        StgType::Optional(inner) => ts_type(inner, brands),
        StgType::Prim(p) => ts_prim(p, brands),
    }
}

fn ts_prim(p: &StgPrim, brands: &mut BTreeSet<String>) -> String {
    use Base::*;
    let base = match p.base {
        Str => "string",
        Int | Float => "number",
        Bool => "boolean",
    };
    // Refinements become branded nominal types so invalid values fail at
    // assignment sites in downstream code.
    let brand_name = brand_for(p);
    match brand_name {
        Some((name, base_ty)) => {
            brands.insert(format!("export type {name} = Brand<{base_ty}, '{name}'>;"));
            name
        }
        None => base.to_owned(),
    }
}

/// Derives a branded type name from refinements/format, if warranted.
fn brand_for(p: &StgPrim) -> Option<(String, &'static str)> {
    if p.base != Base::Str {
        return None;
    }
    let name = if let Some(pattern) = &p.refs.pattern {
        let words: Vec<String> = suspect_gen::split_words(pattern)
            .iter()
            .map(|w| {
                let mut c = w.chars();
                match c.next() {
                    Some(f) => f.to_uppercase().collect::<String>() + c.as_str(),
                    None => String::new(),
                }
            })
            .collect();
        format!("Pattern{}", words.join(""))
    } else {
        return match &p.refs.format {
            Some(WellKnownFormat::Email) => Some(("Email".to_owned(), "string")),
            Some(WellKnownFormat::Uuid) => Some(("Uuid".to_owned(), "string")),
            Some(WellKnownFormat::DateTime) => Some(("DateTimeIso".to_owned(), "string")),
            Some(WellKnownFormat::Date) => Some(("DateIso".to_owned(), "string")),
            _ => None,
        };
    };
    Some((name, "string"))
}

fn quote_ts(literal: &str) -> String {
    format!("'{}'", literal.replace('\'', "\\'"))
}

fn zod_twin(graph: &Graph) -> (String, String) {
    let mut out = String::from(
        "// Zod schemas mirroring types.ts. Requires `zod` as a dependency.\nimport { z } from 'zod';\n\n",
    );
    for name in &graph.topo_order {
        let Some(StgNode::Struct(s)) = graph.components.get(name) else {
            continue;
        };
        out.push_str(&format!(
            "export const {}Schema = z.object({{\n",
            s.name.camel
        ));
        for f in &s.fields {
            let wrapper = if f.required { "" } else { ".optional()" };
            out.push_str(&format!("  {}: z.unknown(){},\n", f.ident.camel, wrapper));
        }
        out.push_str("});\n\n");
        out.push_str(&format!(
            "export type {0}Inferred = z.infer<typeof {1}Schema>;\n\n",
            s.name.pascal, s.name.camel
        ));
    }
    ("zod.ts".into(), out)
}

fn ts_client(graph: &Graph) -> (String, String) {
    let mut out = String::from(
        "// Fetch-based API client.\n\nexport interface Transport {\n  execute(req: HttpRequest): Promise<HttpResponse>;\n}\n\nexport interface HttpRequest {\n  method: string;\n  url: string;\n  headers: Record<string, string>;\n  body?: string;\n}\n\nexport interface HttpResponse {\n  status: number;\n  body: string;\n}\n\nexport class ApiClient {\n  constructor(private baseUrl: string, private transport: Transport) {}\n\n",
    );
    for op in &graph.operations {
        let path_expr = interpolate_path(&op.path_template, &op.params_path);
        let args: Vec<String> = op
            .params_path
            .iter()
            .chain(op.params_query.iter())
            .map(|p| format!("{}: {}", p.name.camel, ts_type(&p.ty, &mut BTreeSet::new())))
            .collect();
        let body_arg = op
            .request_body
            .as_ref()
            .map(|name| format!("body: {}", crate::stg::Ident::new(name).pascal))
            .unwrap_or_default();
        let mut all_args = args;
        if !body_arg.is_empty() {
            all_args.push(body_arg);
        }
        out.push_str(&format!(
            "  async {}({}): Promise<HttpResponse> {{\n",
            op.op_id.camel,
            all_args.join(", ")
        ));
        out.push_str(&format!(
            "    const url = `${{this.baseUrl}}` + `{path_expr}`;\n"
        ));
        if !op.params_query.is_empty() {
            out.push_str("    const qs = new URLSearchParams();\n");
            for p in &op.params_query {
                out.push_str(&format!(
                    "    qs.set('{}', String({}));\n",
                    p.name.original, p.name.camel
                ));
            }
            out.push_str("    void qs;\n");
        }
        if op.request_body.is_some() {
            out.push_str(
                "    const init: RequestInit = { method: 'METHOD', body: JSON.stringify(body) };\n",
            );
        } else {
            out.push_str("    const init: RequestInit = { method: 'METHOD' };\n");
        }
        out.push_str("    void init;\n    throw new Error('not implemented');\n  }\n\n");
    }
    out.push_str("}\n");
    ("client.ts".into(), out)
}

fn interpolate_path(template: &str, params: &[crate::stg::OpParam]) -> String {
    let mut out = template.to_string();
    for p in params {
        out = out.replace(
            &format!("{{{}}}", p.name.original),
            &format!("${{{}}}", p.name.camel),
        );
    }
    out
}
