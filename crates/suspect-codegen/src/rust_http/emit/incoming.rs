//! Emitted-only incoming receipt helpers for the Rust HTTP adapter. The static
//! runtime gains nothing: every route constant, descriptor, decoder and
//! constructor below is generated into the consumer package only when the plan
//! carries declared webhooks or callbacks, and the whole module disappears when
//! none are declared.
//!
//! HTTP semantics are inverted for these receipts: the declared method is the
//! verb the provider sends and the declared responses are what the handler
//! returns. Decoders presence-check the declared required headers and decode
//! the declared JSON body through the operation's own compiled model codec;
//! constructors build the first declared exact 2xx reply. The compiled receipt
//! descriptors are frozen generated data — the runtime never parses OpenAPI.
//! Route expressions (`{$request...}`) are carried verbatim; their substitution
//! is a runtime/framework concern.

use super::*;
use crate::rust_http::incoming::{
    ConstructedBody, ConstructedResponse, IncomingPayload, IncomingReceipt,
};

/// Everything `package` needs to emit incoming receipt support.
pub(super) struct Emission {
    /// The generated `rust/src/incoming.rs` module content.
    pub(super) module: String,
}

/// Compile the incoming receipt emission for one plan, or `None` when the plan
/// declares no receipts (the package then gains nothing at all).
pub(super) fn emission(plan: &HttpPlan) -> Option<Emission> {
    let receipts = plan.incoming_receipts();
    if receipts.is_empty() {
        return None;
    }
    Some(Emission {
        module: module(plan, receipts),
    })
}

/// A Rust string literal for generated data values.
fn q(value: &str) -> String {
    format!("{value:?}")
}

/// A `crate::http::Source` literal.
fn at(id: &suspect_ir::contract::SourceId) -> String {
    descriptors::source(id)
}

/// Whether any decoder or constructor reads caller-supplied headers.
fn needs_header_value(receipts: &[IncomingReceipt]) -> bool {
    receipts.iter().any(|receipt| {
        !receipt.required_headers.is_empty()
            || receipt
                .response
                .as_ref()
                .is_some_and(|response| !response.headers.is_empty())
    })
}

/// The `receipt_failure` calls a receipt makes: missing required headers, an
/// absent required body, and missing required reply headers.
fn needs_receipt_failure(receipts: &[IncomingReceipt]) -> bool {
    receipts.iter().any(|receipt| {
        !receipt.required_headers.is_empty()
            || receipt.required_body
            || receipt
                .response
                .as_ref()
                .is_some_and(|response| !response.required_headers.is_empty())
    })
}

/// The generated `rust/src/incoming.rs` module: shared receipt library plus the
/// per-receipt compiled helpers and the frozen descriptor constants.
fn module(plan: &HttpPlan, receipts: &[IncomingReceipt]) -> String {
    let mut code = String::from(
        "//! Code generated by suspect. DO NOT EDIT.\n//!\n//! Generated incoming receipt helpers for this package's declared webhooks and\n//! callbacks. HTTP semantics are inverted for these receipts: the declared\n//! method is the verb the provider sends and the declared responses are what\n//! the handler returns. Decoders presence-check the declared required headers\n//! and decode the declared body through the same compiled model codecs the\n//! client uses; constructors build the declared 2xx reply. The compiled receipt\n//! descriptors below are frozen generated data — the runtime never parses\n//! OpenAPI. Route expressions ({$request...}) are carried verbatim; their\n//! substitution is a runtime/framework concern.\n\n",
    );
    code.push_str(TYPES);
    code.push_str(&format!(
        "/// Every declared receipt of this package, in declaration order.\npub static RECEIPTS: &[IncomingDescriptor] = &[{}];\n",
        receipts
            .iter()
            .map(|receipt| receipt.descriptor_const.clone())
            .collect::<Vec<_>>()
            .join(", "),
    ));
    let json_limits = &plan.config.codecs.json_limits;
    let payload_json_failure = receipts
        .iter()
        .any(|receipt| matches!(receipt.payload, IncomingPayload::SchemaFreeJson));
    let reply_json_failure = receipts.iter().any(|receipt| {
        receipt
            .response
            .as_ref()
            .is_some_and(|response| matches!(response.body, Some(ConstructedBody::SchemaFreeJson)))
    });
    let header_value = needs_header_value(receipts);
    let receipt_failure = needs_receipt_failure(receipts);
    if payload_json_failure || reply_json_failure {
        code.push_str(&format!(
            "/// Finite exact JSON budgets compiled from this package's transport policy.\nconst JSON_LIMITS: crate::JsonLimits = crate::JsonLimits {{ max_input_bytes: {}, max_output_bytes: {}, max_depth: {}, max_work: {} }};\n",
            json_limits.max_input_bytes,
            json_limits.max_output_bytes,
            json_limits.max_depth,
            json_limits.max_work,
        ));
    }
    if header_value {
        code.push_str(HEADER_VALUE);
    }
    if receipt_failure {
        code.push_str(RECEIPT_FAILURE);
    }
    if receipts.iter().any(IncomingReceipt::decodes_codec) {
        code.push_str(DECODE_FAILURE);
    }
    if receipts.iter().any(|receipt| {
        receipt
            .response
            .as_ref()
            .is_some_and(|response| matches!(response.body, Some(ConstructedBody::Json { .. })))
    }) {
        code.push_str(CONSTRUCT_FAILURE);
    }
    if payload_json_failure {
        code.push_str(PAYLOAD_JSON_FAILURE);
    }
    if reply_json_failure {
        code.push_str(REPLY_JSON_FAILURE);
    }
    for receipt in receipts {
        code.push_str(&source_const(receipt));
        code.push_str(&route_const(receipt));
        code.push_str(&descriptor_const(receipt));
        code.push_str(&decoder(receipt));
        if let Some(response) = &receipt.response {
            code.push_str(&constructor(receipt, response));
        }
    }
    code
}

/// The frozen public receipt types: generated data, never parsed from OpenAPI.
const TYPES: &str = "/// The declared receipt route of one receipt: `method` is the verb the\n/// provider sends.\n#[derive(Debug, Clone, Copy, PartialEq, Eq)]\npub struct IncomingRoute {\n    /// The verb the provider sends.\n    pub method: &'static str,\n    /// The webhook key, or the callback expression string, exactly as declared.\n    pub route: &'static str,\n    /// True when the route carries RFC 6570 runtime expressions\n    /// (`{$request...}`); their substitution is a runtime/framework concern.\n    pub expression: bool,\n}\n\n/// The frozen compiled descriptor of one declared receipt: generated data,\n/// never parsed from OpenAPI, and sheddable when the consumer references no\n/// receipt helper.\n#[derive(Debug, Clone, Copy, PartialEq, Eq)]\npub struct IncomingDescriptor {\n    /// `\"webhook\"` for a document-level webhooks entry, `\"callback\"` for a\n    /// callbacks entry attached to an operation.\n    pub kind: &'static str,\n    /// The verb the provider sends.\n    pub method: &'static str,\n    /// The receipt route, carried verbatim from the source declaration.\n    pub route: &'static str,\n    /// True when the route carries runtime expressions.\n    pub expression: bool,\n    /// The declaration's source location.\n    pub source: crate::http::Source,\n    /// The declared receipt headers a decoder presence-checks.\n    pub required_headers: &'static [&'static str],\n    /// The decode representation: `\"none\"`, `\"json\"` or\n    /// `\"schema-free-json\"`.\n    pub payload: &'static str,\n    /// The generated model codec of the decoded payload, when it has one.\n    pub payload_codec: std::option::Option<&'static str>,\n    /// The constructed reply representation: `\"none\"`, `\"json\"` or\n    /// `\"schema-free-json\"`.\n    pub reply: &'static str,\n    /// The pinned reply status, when an exact 2xx reply is declared.\n    pub reply_status: std::option::Option<u16>,\n    /// The generated model codec of the reply body, when it has one.\n    pub reply_codec: std::option::Option<&'static str>,\n    /// The declared reply headers a constructor applies.\n    pub reply_headers: &'static [&'static str],\n}\n";

/// Reads one declared receipt header case-insensitively.
const HEADER_VALUE: &str = "/// Reads one declared receipt header case-insensitively.\nfn header_value<'a>(headers: &'a [(String, String)], name: &str) -> std::option::Option<&'a str> {\n    headers\n        .iter()\n        .find(|(key, _)| key.eq_ignore_ascii_case(name))\n        .map(|(_, value)| value.as_str())\n}\n";

/// The branded receipt failure. The runtime's `SdkErrorKind` union is closed,
/// so a receipt that violates its declaration surfaces as a response-decoding
/// failure, exactly like an undecodable response body.
const RECEIPT_FAILURE: &str = "/// A received receipt that violates its declared headers or body. The\n/// runtime's `SdkErrorKind` union is closed, so the branded incoming failure\n/// surfaces as a response-decoding failure, exactly like an undecodable\n/// response body.\nfn receipt_failure(\n    operation: crate::http::Source,\n    source: crate::http::Source,\n    message: impl Into<String>,\n) -> crate::http::SdkError {\n    let mut failure = crate::http::validation_error(operation, source, message);\n    failure.kind = crate::http::SdkErrorKind::ResponseDecoding;\n    failure\n}\n";

/// A decoded receipt payload that failed its declared schema, classified
/// exactly like the per-item decode of a streamed response.
const DECODE_FAILURE: &str = "/// A decoded receipt payload that failed its declared schema: resource-limit\n/// failures stay resource limits and everything else is a response-decoding\n/// failure, exactly like the per-item decode of a streamed response.\nfn decode_failure(\n    operation: crate::http::Source,\n    schema: crate::http::Source,\n    cause: crate::codecs::CodecError,\n) -> crate::http::SdkError {\n    let limited = matches!(&cause, crate::codecs::CodecError::EvaluationFailure(_))\n        || matches!(&cause, crate::codecs::CodecError::Json(json) if json.kind == crate::JsonErrorKind::ResourceLimit)\n        || matches!(&cause, crate::codecs::CodecError::Conversion(finding) if matches!(\n            finding.message.as_str(),\n            \"native conversion work limit exceeded\" | \"native conversion depth limit exceeded\"\n        ));\n    let mut failure = crate::http::validation_error(\n        operation,\n        schema,\n        \"the received payload does not satisfy its declared schema\",\n    );\n    failure.kind = if limited {\n        crate::http::SdkErrorKind::ResourceLimit\n    } else {\n        crate::http::SdkErrorKind::ResponseDecoding\n    };\n    failure.cause = std::option::Option::Some(std::boxed::Box::new(cause));\n    failure\n}\n";

/// A reply value that cannot be constructed into its declared schema,
/// classified exactly like an encoded request input.
const CONSTRUCT_FAILURE: &str = "/// A reply value that cannot be constructed into its declared schema:\n/// classified exactly like an encoded request input, because the reply is the\n/// caller-owned value this receipt writes.\nfn construct_failure(\n    operation: crate::http::Source,\n    schema: crate::http::Source,\n    cause: crate::codecs::CodecError,\n) -> crate::http::SdkError {\n    crate::http::request_codec_error(operation, schema, cause)\n}\n";

/// A schema-free receipt payload that is not valid JSON.
const PAYLOAD_JSON_FAILURE: &str = "/// A schema-free receipt payload that is not valid JSON. The runtime's\n/// `SdkErrorKind` union is closed, so the branded incoming failure surfaces as\n/// a response-decoding failure, exactly like an undecodable response body.\nfn payload_json_failure(\n    operation: crate::http::Source,\n    source: crate::http::Source,\n    error: crate::JsonError,\n) -> crate::http::SdkError {\n    let mut failure = crate::http::validation_error(\n        operation,\n        source,\n        \"the received payload is not valid JSON\",\n    );\n    failure.kind = crate::http::SdkErrorKind::ResponseDecoding;\n    failure.cause = std::option::Option::Some(std::boxed::Box::new(error));\n    failure\n}\n";

/// A schema-free reply value that is not representable JSON.
const REPLY_JSON_FAILURE: &str = "/// A schema-free reply value that is not representable JSON.\nfn reply_json_failure(\n    operation: crate::http::Source,\n    source: crate::http::Source,\n    error: crate::JsonError,\n) -> crate::http::SdkError {\n    let mut failure = crate::http::validation_error(\n        operation,\n        source,\n        \"the reply value is not representable JSON\",\n    );\n    failure.kind = crate::http::SdkErrorKind::RequestRepresentation;\n    failure.cause = std::option::Option::Some(std::boxed::Box::new(error));\n    failure\n}\n";

/// One receipt's declaration source constant.
fn source_const(receipt: &IncomingReceipt) -> String {
    format!(
        "/// The declaration source of the {} {} receipt.\nconst {}: crate::http::Source = {};\n",
        prose(receipt.kind),
        prose(&receipt.name),
        receipt.source_const,
        at(&receipt.source),
    )
}

/// One receipt's declared route constant.
fn route_const(receipt: &IncomingReceipt) -> String {
    let mut code = String::new();
    code.push_str(&format!(
        "/// The declared receipt route of the {} {} receipt: `method` is the verb\n/// the provider sends, and the route string is carried verbatim from the\n/// source declaration. Register a handler at this route in your framework;\n/// runtime expression substitution is a framework concern.\n/// Source: {}#{}.\n",
        prose(receipt.kind),
        prose(&receipt.name),
        prose(receipt.source.document().as_str()),
        prose(receipt.source.pointer()),
    ));
    code.push_str(&format!(
        "pub static {}: IncomingRoute = IncomingRoute {{\n    method: {},\n    route: {},\n    expression: {},\n}};\n",
        receipt.route_const,
        q(&receipt.method),
        q(&receipt.route),
        receipt.expression,
    ));
    code
}

/// One receipt's frozen compiled descriptor constant.
fn descriptor_const(receipt: &IncomingReceipt) -> String {
    let (reply, reply_status, reply_codec, reply_headers) = match &receipt.response {
        None => (
            "none".to_owned(),
            "std::option::Option::None".to_owned(),
            "std::option::Option::None".to_owned(),
            Vec::new(),
        ),
        Some(response) => (
            response
                .body
                .as_ref()
                .map_or_else(|| "none".to_owned(), |body| body.label().to_owned()),
            format!("std::option::Option::Some({})", response.status),
            match &response.body {
                Some(ConstructedBody::Json { model, .. }) => {
                    format!("std::option::Option::Some({})", q(model))
                }
                _ => "std::option::Option::None".to_owned(),
            },
            response.headers.clone(),
        ),
    };
    let mut code = String::new();
    code.push_str(&format!(
        "/// The frozen compiled descriptor of the {} {} receipt: generated data,\n/// never parsed from OpenAPI, and sheddable when the consumer references no\n/// receipt helper. Source: {}#{}.\n",
        prose(receipt.kind),
        prose(&receipt.name),
        prose(receipt.source.document().as_str()),
        prose(receipt.source.pointer()),
    ));
    code.push_str(&format!(
        "pub static {}: IncomingDescriptor = IncomingDescriptor {{\n    kind: {},\n    method: {},\n    route: {},\n    expression: {},\n    source: {},\n    required_headers: &[{}],\n    payload: {},\n    payload_codec: {},\n    reply: {reply:?},\n    reply_status: {reply_status},\n    reply_codec: {reply_codec},\n    reply_headers: &[{reply_headers}],\n}};\n",
        receipt.descriptor_const,
        q(receipt.kind),
        q(&receipt.method),
        q(&receipt.route),
        receipt.expression,
        at(&receipt.source),
        receipt
            .required_headers
            .iter()
            .map(|header| q(header))
            .collect::<Vec<_>>()
            .join(", "),
        q(receipt.payload.label()),
        match receipt.payload.codec() {
            Some(codec) => format!("std::option::Option::Some({})", q(codec)),
            None => "std::option::Option::None".to_owned(),
        },
        reply_headers = reply_headers
            .iter()
            .map(|header| q(header))
            .collect::<Vec<_>>()
            .join(", "),
    ));
    code
}

/// One receipt's decoder: declared required headers are presence-checked and
/// the declared body decodes through the operation's own compiled codec.
fn decoder(receipt: &IncomingReceipt) -> String {
    let mut doc = format!(
        "Decode one received {} receipt of the {} `{}`. Declared required\n/// headers are presence-checked (a missing one fails with the branded receipt\n/// error) and the declared body decodes through the operation's own compiled\n/// codec machinery.",
        receipt.method, receipt.kind, receipt.name,
    );
    if !receipt.explanations.is_empty() {
        doc.push_str("\n///\n/// ");
        doc.push_str(&receipt.explanations.join(" "));
    }
    let mut code = format!(
        "/// {doc}\n/// Source: {}#{}.\npub fn {}(\n    headers: &[(String, String)],\n    body: &[u8],\n) -> std::result::Result<{}, crate::http::SdkError> {{\n",
        prose(receipt.source.document().as_str()),
        prose(receipt.source.pointer()),
        receipt.decode,
        receipt.payload_type(),
    );
    if receipt.required_headers.is_empty() {
        code.push_str("    let _ = headers;\n");
    }
    if matches!(receipt.payload, IncomingPayload::None) {
        code.push_str("    let _ = body;\n");
    }
    for header in &receipt.required_headers {
        code.push_str(&format!(
            "    if header_value(headers, {header}).is_none() {{\n        return std::result::Result::Err(receipt_failure(\n            {source},\n            {source},\n            {message},\n        ));\n    }}\n",
            header = q(header),
            source = receipt.source_const,
            message = q(&format!("required receipt header {header} is absent")),
        ));
    }
    if receipt.required_body {
        code.push_str(&format!(
            "    if body.is_empty() {{\n        return std::result::Result::Err(receipt_failure(\n            {source},\n            {source},\n            \"the declared required receipt body is absent\",\n        ));\n    }}\n",
            source = receipt.source_const,
        ));
    }
    match &receipt.payload {
        IncomingPayload::None => code.push_str("    std::result::Result::Ok(())\n}\n"),
        IncomingPayload::Json { model, schema } => code.push_str(&format!(
            "    crate::codecs::{model}Codec::decode_bytes(body).map_err(|cause| {{\n        decode_failure({}, {}, cause)\n    }})\n}}\n",
            receipt.source_const,
            at(schema),
        )),
        IncomingPayload::SchemaFreeJson => code.push_str(&format!(
            "    crate::parse_json_bytes(body, JSON_LIMITS).map_err(|error| {{\n        payload_json_failure({}, {}, error)\n    }})\n}}\n",
            receipt.source_const,
            receipt.source_const,
        )),
    }
    code
}

/// One receipt's reply constructor, when an exact 2xx response is declared.
fn constructor(receipt: &IncomingReceipt, response: &ConstructedResponse) -> String {
    let Some(construct) = &receipt.construct else {
        return String::new();
    };
    let has_body = response.body.is_some();
    let has_headers = !response.headers.is_empty();
    let mut parameters = String::new();
    if has_body {
        let value = match &response.body {
            Some(ConstructedBody::Json { model, .. }) => format!("&crate::models::{model}"),
            Some(ConstructedBody::SchemaFreeJson) => "&crate::JsonValue".to_owned(),
            None => "()".to_owned(),
        };
        parameters.push_str("result: ");
        parameters.push_str(&value);
        if has_headers {
            parameters.push_str(",\n    ");
        }
    }
    if has_headers {
        parameters.push_str("typed_headers: &[(String, String)]");
    }
    let mut doc = format!(
        "Construct the declared `{}` reply of the {} `{}` receipt: the returned\n/// tuple carries the declared status, the encoded body and the applied\n/// declared headers.",
        response.status, receipt.kind, receipt.name,
    );
    if !receipt.explanations.is_empty() {
        doc.push_str("\n///\n/// ");
        doc.push_str(&receipt.explanations.join(" "));
    }
    let signature = if parameters.is_empty() {
        format!("pub fn {construct}()")
    } else {
        format!("pub fn {construct}(\n    {parameters}\n)")
    };
    let mut code = format!(
        "/// {doc}\n/// Source: {}#{}.\n{signature} -> std::result::Result<(u16, std::vec::Vec<(String, String)>, std::vec::Vec<u8>), crate::http::SdkError> {{\n",
        prose(receipt.source.document().as_str()),
        prose(receipt.source.pointer()),
    );
    if has_headers {
        let optional = response
            .headers
            .iter()
            .filter(|header| !response.required_headers.contains(header))
            .cloned()
            .collect::<Vec<_>>();
        code.push_str("    let mut reply_headers = std::vec::Vec::new();\n");
        if !optional.is_empty() {
            code.push_str(&format!(
                "    for name in [{}] {{\n        if let std::option::Option::Some(value) = header_value(typed_headers, name) {{\n            reply_headers.push((\n                std::string::String::from(name),\n                std::string::String::from(value),\n            ));\n        }}\n    }}\n",
                optional.iter().map(|header| q(header)).collect::<Vec<_>>().join(", "),
            ));
        }
        if !response.required_headers.is_empty() {
            code.push_str(&format!(
                "    for name in [{}] {{\n        let std::option::Option::Some(value) = header_value(typed_headers, name) else {{\n            return std::result::Result::Err(receipt_failure(\n                {source},\n                {source},\n                format!(\"the declared required reply header {{name}} is absent\"),\n            ));\n        }};\n        reply_headers.push((\n            std::string::String::from(name),\n            std::string::String::from(value),\n        ));\n    }}\n",
                response
                    .required_headers
                    .iter()
                    .map(|header| q(header))
                    .collect::<Vec<_>>()
                    .join(", "),
                source = receipt.source_const,
            ));
        }
    }
    let body = match &response.body {
        Some(ConstructedBody::Json { model, schema }) => format!(
            "let body = crate::codecs::{model}Codec::encode(result)\n        .map_err(|cause| construct_failure({}, {}, cause))?\n        .into_bytes();\n    ",
            receipt.source_const,
            at(schema),
        ),
        Some(ConstructedBody::SchemaFreeJson) => format!(
            "let body = crate::stringify_json(result, JSON_LIMITS)\n        .map_err(|error| reply_json_failure({}, {}, error))?\n        .into_bytes();\n    ",
            receipt.source_const, receipt.source_const,
        ),
        None => String::new(),
    };
    let headers_expression = if has_headers {
        "reply_headers"
    } else {
        "std::vec::Vec::new()"
    };
    let bytes = if has_body {
        "body".to_owned()
    } else {
        "std::vec::Vec::new()".to_owned()
    };
    code.push_str(&format!(
        "    {body}std::result::Result::Ok(({}, {headers_expression}, {bytes}))\n}}\n",
        response.status,
    ));
    code
}
