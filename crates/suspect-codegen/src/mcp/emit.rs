//! Emit one self-contained private ESM package: package metadata, the
//! generated tool registrations and stdio entry point, the hand-written
//! tool-call runtime, the canonical SDK as an embedded source directory, a
//! guide and the deterministic surface manifest.
//!
//! Nothing here decides a public name, a schema or a wire semantic; all three
//! were fixed during admission.
use std::{collections::BTreeMap, fmt::Write as _};

use super::{
    LogPolicy, ServerPlan, package,
    planning::{BoundInput, BoundResponse, BoundTool},
    surface,
};
use crate::OutFile;

/// Embedded SDK reference documents kept beside the sources, so an application
/// owner can review exactly what the operations and codecs do.
const SDK_DOCUMENTATION: &[&str] = &[
    "typescript/codecs.md",
    "typescript/docs-manifest.json",
    "typescript/http-manifest.json",
    "typescript/http.md",
    "typescript/models.md",
    "typescript/validation.md",
];

/// A single-quoted TypeScript string literal.
fn q(text: &str) -> String {
    let mut out = String::with_capacity(text.len() + 2);
    out.push('\'');
    for character in text.chars() {
        match character {
            '\'' => out.push_str("\\'"),
            '\\' => out.push_str("\\\\"),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\u{2028}' => out.push_str("\\u2028"),
            '\u{2029}' => out.push_str("\\u2029"),
            other if other.is_control() => {
                let _ = write!(out, "\\u{:04x}", u32::from(other));
            }
            other => out.push(other),
        }
    }
    out.push('\'');
    out
}

/// Collapse prose onto one line so it can never break a generated comment.
fn prose(text: &str) -> String {
    text.replace(['\n', '\r'], " ").replace("*/", "* /")
}

pub(super) fn artifacts(plan: &ServerPlan) -> Vec<OutFile> {
    // The SDK becomes a source directory of this one package, so its own
    // package metadata, lockfile, build configuration, guide and
    // self-importing examples are dropped: this output root owns exactly one
    // installable package.
    let mut files: BTreeMap<String, String> = plan
        .sdk_files
        .iter()
        .filter(|file| {
            let path = file.path.as_str();
            assert!(
                path.starts_with("typescript/"),
                "canonical TypeScript SDK artifact"
            );
            (path.ends_with(".ts") && !path.starts_with("typescript/examples/"))
                || SDK_DOCUMENTATION.contains(&path)
        })
        .map(|file| (file.path.clone(), file.content.clone()))
        .collect();
    for file in package::artifacts(plan) {
        files.insert(file.path, file.content);
    }
    files.insert("server/main.ts".into(), main(plan));
    files.insert(
        "server/runtime.ts".into(),
        include_str!("runtime.ts").into(),
    );
    files.insert("README.md".into(), readme(plan));
    let manifest = surface::artifact(plan);
    files.insert(manifest.path, manifest.content);
    files
        .into_iter()
        .map(|(path, content)| OutFile { path, content })
        .collect()
}

/// `METHOD /path (operationId)`, the one phrase every diagnostic names.
fn target(plan: &ServerPlan, tool: &BoundTool) -> String {
    let operation = &plan.sdk.operations()[tool.operation];
    format!(
        "{} {} ({})",
        operation.protocol().method().as_str(),
        operation.path,
        operation.operation_id
    )
}

#[allow(clippy::too_many_lines)]
fn main(plan: &ServerPlan) -> String {
    let config = &plan.config;
    let mut code =
        String::from("#!/usr/bin/env node\n// Code generated by suspect. DO NOT EDIT.\n\n");
    let _ = write!(
        code,
        "/**\n\
         \x20* Generated stdio Model Context Protocol server for {}.\n\
         \x20*\n\
         \x20* {}\n\
         \x20*\n\
         \x20* Standard output carries MCP protocol traffic exclusively; every\n\
         \x20* diagnostic goes to standard error. Every HTTP, authentication,\n\
         \x20* validation and exact JSON decision lives in the embedded canonical\n\
         \x20* SDK under typescript/, and every tool-call bound, cancellation and\n\
         \x20* failure decision lives in ./runtime.ts. This module only registers\n\
         \x20* the explicitly mapped tools.\n\
         \x20*\n\
         \x20* No tool input carries a credential or a filesystem path, and no\n\
         \x20* resource, prompt, retry or pagination traversal is generated.\n\
         \x20*/\n",
        prose(&config.server_name),
        prose(&plan.mapping.description),
    );
    code.push_str(
        "import { McpServer, fromJsonSchema } from '@modelcontextprotocol/server';\n\
         import { StdioServerTransport } from '@modelcontextprotocol/server/stdio';\n\n\
         import * as Codecs from '../typescript/model-codecs.js';\n\
         import * as Operations from '../typescript/operations.js';\n\
         import {\n\
         \x20   baseUrl,\n\
         \x20   keepStandardOutputForProtocol,\n\
         \x20   runTool,\n\
         \x20   toNativeInput,\n\
         \x20   type Adapter,\n\
         \x20   type Policy,\n\
         \x20   type Reply,\n\
         \x20   type ResponseBinding,\n\
         } from './runtime.js';\n\n",
    );
    let _ = write!(
        code,
        "const SERVER_NAME = {};\n\
         const SERVER_VERSION = {};\n\
         const SERVER_URL_ENV: string | null = {};\n\
         const CALL_DEADLINE_MS = {};\n\
         const MAX_INPUT_BYTES = {};\n\
         const MAX_RESULT_BYTES = {};\n\
         const LOG_POLICY = {};\n\
         /** Finite bounds compiled from the application target configuration.\n\
         \x20* A client cannot raise any of them. */\n\
         const POLICY: Policy = {{\n\
         \x20   deadlineMs: CALL_DEADLINE_MS,\n\
         \x20   maxInputBytes: MAX_INPUT_BYTES,\n\
         \x20   maxResultBytes: MAX_RESULT_BYTES,\n\
         \x20   logs: LOG_POLICY,\n\
         }};\n\n",
        q(&config.server_name),
        q(&config.version),
        config
            .server_url_env
            .as_deref()
            .map_or_else(|| "null".to_owned(), q),
        config.runtime.call_deadline_ms,
        config.runtime.max_input_bytes,
        config.runtime.max_result_bytes,
        q(match config.logs.policy {
            LogPolicy::Off => "off",
            LogPolicy::Failures => "failures",
            LogPolicy::Calls => "calls",
        }),
    );
    code.push_str(
        "keepStandardOutputForProtocol();\n\n\
         // Credentials come only from the explicitly configured environment\n\
         // variables, snapshotted by the generated SDK's own factory when this\n\
         // process starts. This module never reads one, and no tool input ever\n\
         // carries one.\n\
         const client = Operations.createClient(baseUrl(SERVER_URL_ENV));\n\
         const server = new McpServer({ name: SERVER_NAME, version: SERVER_VERSION });\n\n",
    );

    for tool in &plan.tools {
        code.push_str(&declarations(plan, tool));
    }
    // Registration is one unconditional, purely declarative block: the listed
    // order and every listed schema come from the mapping, so tools/list can
    // never depend on runtime state, an environment read or a network reply.
    code.push_str(
        "// Deterministic discovery: tool order, schemas and annotations all come\n\
         // from the generated plan, never from runtime state.\n",
    );
    for tool in &plan.tools {
        code.push_str(&registration(plan, tool));
    }
    code.push_str("await server.connect(new StdioServerTransport());\n");
    code
}

fn declarations(plan: &ServerPlan, tool: &BoundTool) -> String {
    let operation = &plan.sdk.operations()[tool.operation];
    let symbol = &tool.symbol;
    let mut code = format!("// {} -> {}\n", tool.name, target(plan, tool));
    let _ = writeln!(
        code,
        "const schema_{symbol} = {} as const;",
        serde_json::to_string_pretty(&input_schema(tool)).expect("projected schema is JSON")
    );
    for (index, input) in tool.inputs.iter().enumerate() {
        let _ = writeln!(
            code,
            "const adapter_{symbol}_{index}: Adapter = {};",
            serde_json::to_string(&input.adapter.literal()).expect("adapter literal is JSON")
        );
    }
    let _ = write!(
        code,
        "const success_{symbol}: readonly ResponseBinding[] = [{}];\n\
         const failure_{symbol}: readonly ResponseBinding[] = [{}];\n",
        bindings(&tool.responses, true),
        bindings(&tool.responses, false),
    );
    // The argument phase is its own function so a rejected argument can never
    // be reported as a condition at the API: nothing is sent until it returns.
    // The generated codecs enforce every source assertion the projected schema
    // deliberately does not carry.
    let _ = write!(
        code,
        "function bind_{symbol}(args: Record<string, unknown>): Operations.{} {{\n\
         \x20   const input: Operations.{} = {{{}}};\n",
        operation.input_type,
        operation.input_type,
        required(tool),
    );
    for (index, input) in tool.inputs.iter().enumerate() {
        if input.required {
            continue;
        }
        // An omitted optional property stays omitted on the wire: presence is
        // decided by the argument object, never by a zero, false or empty value.
        let _ = write!(
            code,
            "\x20   if (Object.hasOwn(args, {property})) {{\n\
             \x20       input.{member} = {decode};\n\
             \x20   }}\n",
            property = q(&input.property),
            member = input.member,
            decode = decode(symbol, index, input),
        );
    }
    let _ = write!(
        code,
        "\x20   return input;\n}}\n\
         async function call_{symbol}(input: Operations.{}, signal: AbortSignal): Promise<Reply> {{\n\
         \x20   const reply = await client.{}(input, {{ signal }});\n\
         \x20   return {{ status: reply.status, mediaType: reply.mediaType, data: reply.data }};\n\
         }}\n\n",
        operation.input_type, operation.function_name,
    );
    code
}

/// The object literal of required input members, which the projected schema
/// guarantees are present.
fn required(tool: &BoundTool) -> String {
    let members: Vec<String> = tool
        .inputs
        .iter()
        .enumerate()
        .filter(|(_, input)| input.required)
        .map(|(index, input)| {
            format!(
                "\n        {}: {},",
                input.member,
                decode(&tool.symbol, index, input)
            )
        })
        .collect();
    if members.is_empty() {
        String::new()
    } else {
        format!("{}\n    ", members.concat())
    }
}

/// One argument becomes exact JSON text, then a native model through the
/// generated codec. Ordinary JSON handling never touches an SDK model, and a
/// codec rejection is attributed to this exact public property name.
fn decode(symbol: &str, index: usize, input: &BoundInput) -> String {
    format!(
        "toNativeInput(Codecs.{}, args[{property}], adapter_{symbol}_{index}, {property})",
        input.codec,
        property = q(&input.property),
    )
}

/// The response bindings for one direction: the concrete statuses each declared
/// response selects, and the codec for the body those statuses carry.
fn bindings(responses: &[BoundResponse], success: bool) -> String {
    let mut entries = Vec::new();
    for response in responses {
        let (document, empty) = if success {
            (&response.success_document, &response.success_empty)
        } else {
            (&response.failure_document, &response.failure_empty)
        };
        if !document.is_empty() {
            entries.push(format!(
                "{{ statuses: {}, codec: Codecs.{} }}",
                serde_json::to_string(document).expect("statuses are JSON"),
                response
                    .codec
                    .as_deref()
                    .expect("a body-carrying response has a codec"),
            ));
        }
        if !empty.is_empty() {
            entries.push(format!(
                "{{ statuses: {}, codec: null }}",
                serde_json::to_string(empty).expect("statuses are JSON"),
            ));
        }
    }
    entries.join(", ")
}

fn registration(plan: &ServerPlan, tool: &BoundTool) -> String {
    let operation = &plan.sdk.operations()[tool.operation];
    let symbol = &tool.symbol;
    format!(
        "server.registerTool(\n\
         \x20   {name},\n\
         \x20   {{\n\
         \x20       title: {title},\n\
         \x20       description: {description},\n\
         \x20       inputSchema: fromJsonSchema<Record<string, unknown>>(schema_{symbol}),\n\
         \x20       annotations: {{\n\
         \x20           title: {title},\n\
         \x20           readOnlyHint: {read_only},\n\
         \x20           destructiveHint: {destructive},\n\
         \x20           idempotentHint: {idempotent},\n\
         \x20           openWorldHint: {open_world},\n\
         \x20       }},\n\
         \x20   }},\n\
         \x20   (args, ctx) =>\n\
         \x20       runTool(\n\
         \x20           {{\n\
         \x20               tool: {name},\n\
         \x20               target: {target},\n\
         \x20               success: success_{symbol},\n\
         \x20               failure: failure_{symbol},\n\
         \x20               declaredFailure: Operations.{guard},\n\
         \x20               bindArguments: bind_{symbol},\n\
         \x20               call: call_{symbol},\n\
         \x20           }},\n\
         \x20           POLICY,\n\
         \x20           args,\n\
         \x20           ctx,\n\
         \x20       ),\n\
         );\n\n",
        name = q(&tool.name),
        title = q(&prose(&tool.title)),
        description = q(&prose(&tool.description)),
        target = q(&target(plan, tool)),
        guard = operation.error_guard,
        read_only = tool.annotations.read_only,
        destructive = tool.annotations.destructive,
        idempotent = tool.annotations.idempotent,
        open_world = tool.annotations.open_world,
    )
}

/// The complete projected tool input schema. `additionalProperties` is always
/// false, so an undeclared argument is refused rather than silently dropped.
fn input_schema(tool: &BoundTool) -> serde_json::Value {
    let mut properties = serde_json::Map::new();
    let mut required = Vec::new();
    for input in &tool.inputs {
        properties.insert(input.property.clone(), input.schema.clone());
        if input.required {
            required.push(serde_json::Value::from(input.property.clone()));
        }
    }
    serde_json::json!({
        "$schema": "https://json-schema.org/draft/2020-12/schema",
        "type": "object",
        "properties": properties,
        "required": required,
        "additionalProperties": false,
    })
}

